// Definition-led: A-VUE-2-0001 D/G/J/K (active Adapter profile); compiler
// preservation requirements C-LIFECYCLE-0003 A/C/I, M-STATE-0001 D/F,
// C-TEMPLATE-0001 A/C, -0002 A, -0005 E (draft). This does not promote
// those drafts or require a RuntimeSession in a native compiler output.
// Error retention is a compatibility regression, NOT a newly defined general
// render-error recovery guarantee. Fault injection below is not public mutation API.
function authored(reuse = false, name = 'commit-contract') {
  return `import {definePrototype} from '@proto.ui/core';
export default definePrototype({name:${JSON.stringify(name)},setup(def){
  def.props.define({present:{type:'boolean',default:true}});
  def.props.watch(['present'],(run,next)=>{run.lifecycle.setPresent(next.present);});
  const value=def.state.string('value','A');
  const probe={value:'x'};
  def.expose.value('probe',probe);
  def.expose.method('write',(next:string)=>{value.set(next);});
  def.expose.method('read',()=>value.get());
  return r=>{
    const read=()=>probe.value;
    const alias=read;
    const selected=()=>{if(true)return 'selected';return alias();};
    ${reuse ? 'const first=alias();' : ''}
    return r.el('commit-node',[
      r.el('output',value.get()),
      r.el('i',${reuse ? 'first' : 'alias()'}),
      r.el('b',${reuse ? 'first' : 'alias()'}),
      r.el('small',selected()),
      r.slot()
    ]);
  };
}});`;
}
// Optional public-safe evidence for the fixed isolated runner. Only fixture text,
// actual generated bytes, compile diagnostics and explicit test metadata are saved;
// no environment dump, source filesystem crawl, credentials or user data.
// Capture failures fail the test rather than silently dropping evidence.
const evidenceRoot = process.env.PUI_VUE2_CONTRACT_EVIDENCE_DIR;
const moduleEvidence = new WeakMap<GeneratedModule, string>();
let evidenceBytes = 0;
let evidenceCompilations = 0;
function artifact(directory: string | undefined, relative: string, contents: string) {
  if (!directory) return;
  if (path.posix.isAbsolute(relative) || relative.includes('\\') ||
    relative.split('/').some(part => !part || part === '..' || part === '.'))
    throw new Error(`Unsafe evidence path ${relative}`);
  const bytes = Buffer.byteLength(contents);
  evidenceBytes += bytes;
  if (bytes > 8 * 1024 * 1024 || evidenceBytes > 64 * 1024 * 1024)
    throw new Error('Generated evidence exceeds fixed byte budget');
  const destination = path.join(directory, relative);
  mkdirSync(path.dirname(destination), { recursive: true });
  writeFileSync(destination, contents, { flag: 'wx' });
}
function artifactJson(directory: string | undefined, relative: string, value: unknown) {
  artifact(directory, relative, JSON.stringify(value, null, 2) + '\n');
}
function beginEvidence(input: string, reuse: boolean, name: string | undefined) {
  if (!evidenceRoot) return undefined;
  if (!path.isAbsolute(evidenceRoot) || ++evidenceCompilations > 16)
    throw new Error('Unexpected fixed evidence root or compilation count');
  mkdirSync(evidenceRoot, { recursive: true });
  const directory = mkdtempSync(path.join(evidenceRoot, 'compile-'));
  artifact(directory, 'authored.proto.ts', input);
  artifactJson(directory, 'input.json', {
    test: expect.getState().currentTestName, reuse, name: name ?? 'commit-contract',
    authoredSha256: createHash('sha256').update(input).digest('hex'),
    typescript: ts.version, vue: Vue2.version,
    note: 'Actual emitter result; behavioral transpilation is not strict validation.',
  });
  return directory;
}
function preserveModule(directory: string | undefined, module: GeneratedModule, prefix = 'emitted') {
  if (!directory) return;
  // Complete GeneratedModule (including maps/dependency/provenance/style metadata)
  // is retained before graph admission or runtime evaluation can fail.
  artifactJson(directory, `${prefix}/module.json`, module);
  const files = [{ path: 'Component.js', kind: 'source', contents: module.code },
    ...(module.supportingFiles ?? [])];
  if (files.length > 256) throw new Error('Generated evidence exceeds fixed file budget');
  for (const file of files) artifact(directory, `${prefix}/files/${file.path}`, file.contents);
  if (directory) moduleEvidence.set(module, directory);
}
function compile(reuse = false, name?: string): GeneratedModule {
  const input = authored(reuse, name);
  const directory = beginEvidence(input, reuse, name);
  const parsed = parsePrototype(input, { fileName: 'commit-contract.proto.ts' });
  artifactJson(directory, 'parse.json', parsed.ok ? { ok: true } : parsed);
  if (!parsed.ok) throw new Error(JSON.stringify(parsed.diagnostics));
  const emitted = emitVue2Source(parsed.value);
  artifactJson(directory, 'emit.json', emitted.ok ? { ok: true } : emitted);
  if (!emitted.ok) throw new Error(JSON.stringify(emitted.diagnostics));
  preserveModule(directory, emitted.value);
  return emitted.value;
}
function diagnosticRecord(diagnostic: ts.Diagnostic): unknown {
  return {
    category: diagnostic.category, code: diagnostic.code,
    file: diagnostic.file?.fileName, start: diagnostic.start, length: diagnostic.length,
    messageText: diagnostic.messageText,
    message: ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'),
    relatedInformation: diagnostic.relatedInformation?.map(diagnosticRecord),
  };
}
function graph(module: GeneratedModule) {
  const files = new Map<string, string>();
  for (const file of [{ path: 'Component.js', kind: 'source', contents: module.code },
    ...(module.supportingFiles ?? [])]) {
    if (file.kind !== 'source' || path.posix.isAbsolute(file.path) || file.path.includes('\\') ||
      file.path.split('/').some(part => !part || part === '..' || part === '.') || files.has(file.path))
      throw new Error(`Unexpected generated artifact ${file.path}`);
    files.set(file.path, file.contents);
  }
  return files;
}
// Actual emitted graph only; no handwritten component, authored runtime import,
// adapter launcher, semantic runtime stub, or replacement template interpreter.
function evaluate(module: GeneratedModule): ComponentOptions<Vue2> {
  const files = graph(module), cache = new Map<string, Record<string, unknown>>();
  function load(file: string): Record<string, unknown> {
    const cached = cache.get(file);
    if (cached) return cached;
    const source = files.get(file);
    if (source === undefined) throw new Error(`Missing generated file ${file}`);
    const exports: Record<string, unknown> = {};
    cache.set(file, exports);
    const javascript = ts.transpileModule(source, { fileName: file, compilerOptions: {
      target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS,
    } }).outputText;
    new Function('require', 'exports', javascript)((specifier: string) => {
      if (specifier === 'vue') return Vue2;
      if (!specifier.startsWith('.')) throw new Error(`Unexpected dependency ${specifier}`);
      const base = path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier));
      const resolved = [base, `${base}.ts`, `${base}.js`].find(candidate => files.has(candidate));
      if (!resolved) throw new Error(`Unclosed generated dependency ${specifier}`);
      return load(resolved);
    }, exports);
    return exports;
  }
  const options = load('Component.js').default;
  if (!options || typeof options !== 'object') throw new Error('Missing actual component options');
  return options as ComponentOptions<Vue2>;
}
function method(object: unknown, name: string): (...args: unknown[]) => unknown {
  if (!object || (typeof object !== 'object' && typeof object !== 'function'))
    throw new Error(`Missing receiver for ${name}`);
  const fn: unknown = Reflect.get(object, name);
  if (typeof fn !== 'function') throw new Error(`Missing method ${name}`);
  return (...args) => Reflect.apply(fn, object, args);
}
const cleanups: Array<() => void | Promise<void>> = [];
afterEach(async () => { for (const cleanup of cleanups.splice(0).reverse()) await cleanup(); });
async function flush() {
  await Vue2.nextTick(); await Promise.resolve(); await Vue2.nextTick();
}
type Mutation = 'none' | 'rerender-authored' | 'freeze-vnode';
async function mount(module = compile(), mutation: Mutation = 'none', keepAlive = false) {
  const options = evaluate(module);
  options.components = { ...options.components, 'commit-node': { render(h: CreateElement) { return h('aside', 'HIJACKED'); } } };
  const render = options.render;
  if (!render) throw new Error('Missing native render');
  // Consumer-side semantic negative controls wrap the REAL generated options.
  // They never replace their emitted renderer with handwritten compiled output.
  let previous: ReturnType<typeof render> | undefined;
  if (mutation !== 'none') options.render = function(h, context) {
    if (mutation === 'freeze-vnode' && previous) return previous;
    const next = render.call(this, h, context);
    previous = next;
    return next;
  };
  const input = Vue2.observable({ slot: 'S0', visible: true, present: true });
  const host = document.createElement('div'); document.body.append(host);
  const app = new Vue2({
    render(h) {
      const child = input.visible ? h(options, { ref: 'compiled', key: 'one', props: { present: input.present },
        scopedSlots: { default: () => [h('em', { attrs: { 'data-native-slot': '' } }, input.slot)] },
      }) : h('span', 'away');
      return keepAlive ? h('keep-alive', [child]) : child;
    },
  });
  let destroyed = false;
  const close = async () => { if (!destroyed) { destroyed = true; app.$destroy(); } host.remove(); await flush(); };
  cleanups.push(close);
  app.$mount(); host.append(app.$el);
  await flush();
  const child = app.$refs.compiled;
  const exposed = method(child, 'getExposes')();
  const update = method(child, 'update');
  return { host, input, child, exposed, update, close,
    async slot(value: string) {
      input.slot = value;
      if (mutation === 'rerender-authored') update();
      await flush();
    },
  };
}
function snapshot(host: HTMLElement) {
  return { authored: host.querySelector('output')?.textContent,
    slot: host.querySelector('[data-native-slot]')?.textContent,
    first: host.querySelector('i')?.textContent, second: host.querySelector('b')?.textContent };
}
async function commitJourney(mutation: Mutation = 'none', name?: string) {
  const view = await mount(compile(false, name), mutation);
  expect(snapshot(view.host)).toMatchObject({ authored: 'A', slot: 'S0' });
  method(view.exposed, 'write')('B');
  expect(method(view.exposed, 'read')()).toBe('B');
  await view.slot('S1');
  expect(snapshot(view.host)).toMatchObject({ authored: 'A', slot: 'S1' });
  view.update(); await flush();
  expect(snapshot(view.host)).toMatchObject({ authored: 'B', slot: 'S1' });
  expect(view.host.querySelector('commit-node')).not.toBeNull();
  expect(view.host.textContent).not.toContain('HIJACKED');
  return view;
}
function installReadProbe(exposed: unknown, get: () => string) {
  if (!exposed || typeof exposed !== 'object') throw new Error('Missing expose record');
  const probe: unknown = Reflect.get(exposed, 'probe');
  if (!probe || typeof probe !== 'object') throw new Error('Missing probe record');
  // Host-only observation/fault injection into an actual emitted captured record;
  // not an assertion that users may mutate an Expose value in production.
  const descriptor = Object.getOwnPropertyDescriptor(probe, 'value');
  if (!descriptor) throw new Error('Missing value descriptor');
  Object.defineProperty(probe, 'value', { configurable: true, enumerable: true, get });
  cleanups.push(() => { Object.defineProperty(probe, 'value', descriptor); });
}
async function helperJourney(reuse = false) {
  const view = await mount(compile(reuse));
  const reads: string[] = [];
  installReadProbe(view.exposed, () => { const value = `read-${reads.length + 1}`; reads.push(value); return value; });
  view.update(); await flush();
  expect(reads).toEqual(['read-1', 'read-2']);
  expect(snapshot(view.host)).toMatchObject({ first: 'read-1', second: 'read-2' });
  expect(view.host.querySelector('small')?.textContent).toBe('selected');
  await view.slot('S1');
  expect(reads).toEqual(['read-1', 'read-2']);
  view.update(); await flush();
  expect(reads).toEqual(['read-1', 'read-2', 'read-3', 'read-4']);
}

describe('Vue2 actual generated committed-authored / live-native-slot boundary', () => {
  it.each(['commit-contract', 'Button', 'RenamedNativeOwner'])('preserves A/S1 then B/S1 without identity dispatch: %s', async name => {
    await commitJourney('none', name);
  });
  it.each(['rerender-authored', 'freeze-vnode'] as const)('rejects the independent %s semantic negative', async mutation => {
    const view = await mount(compile(), mutation);
    expect(snapshot(view.host)).toMatchObject({ authored: 'A', slot: 'S0' });
    method(view.exposed, 'write')('B');
    expect(method(view.exposed, 'read')()).toBe('B');
    await view.slot('S1');
    expect(snapshot(view.host)).toMatchObject(mutation === 'rerender-authored'
      ? { authored: 'B', slot: 'S1' } : { authored: 'A', slot: 'S0' });
    expect(snapshot(view.host)).not.toMatchObject({ authored: 'A', slot: 'S1' });
  });
  it('evaluates a helper alias twice left-to-right, not its unselected branch or live slot refresh', async () => {
    await helperJourney();
  });
  it('rejects source-level reuse of one helper result for two distinct calls', async () => {
    const view = await mount(compile(true));
    expect(snapshot(view.host)).toMatchObject({ authored: 'A', slot: 'S0', first: 'x', second: 'x' });
    const reads: string[] = [];
    installReadProbe(view.exposed, () => { const value = `read-${reads.length + 1}`; reads.push(value); return value; });
    view.update(); await flush();
    expect(reads).toEqual(['read-1']);
    expect(snapshot(view.host)).toMatchObject({ first: 'read-1', second: 'read-1' });
    expect(reads).not.toEqual(['read-1', 'read-2']);
  });
  it('compatibility: a second read failure retains the entire preceding publication', async () => {
    const view = await mount();
    method(view.exposed, 'write')('B');
    const failure = new Error('second authored read'); let reads = 0;
    installReadProbe(view.exposed, () => { if (++reads === 2) throw failure; return 'new-first'; });
    expect(() => view.update()).toThrow(failure);
    expect(reads).toBe(2);
    await view.slot('S1');
    expect(snapshot(view.host)).toEqual({ authored: 'A', slot: 'S1', first: 'x', second: 'x' });
    view.update(); await flush();
    expect(reads).toBe(4);
    expect(snapshot(view.host)).toEqual({ authored: 'B', slot: 'S1', first: 'new-first', second: 'new-first' });
  });
  it('rejects premature clearing of the real generated publication before a throwing read', async () => {
    const module = compile();
    // Source-bound mutation guard: a future lowering must supply its equivalent
    // mutation site explicitly; absence is failure, never skip or vacuous pass.
    const site = 'try { template = renderFunction(renderer); }';
    expect(module.code.split(site)).toHaveLength(2);
    const mutated = { ...module, code: module.code.replace(site,
      'try { template = null; template = renderFunction(renderer); }') };
    preserveModule(moduleEvidence.get(module), mutated, 'negative-premature-clear');
    artifactJson(moduleEvidence.get(mutated), 'negative-premature-clear/mutation.json', {
      original: 'emitted/files/Component.js', site,
      replacement: 'try { template = null; template = renderFunction(renderer); }',
      note: 'Explicit negative only; original emitted graph is preserved unchanged.',
    });
    const view = await mount(mutated);
    expect(snapshot(view.host)).toEqual({ authored: 'A', slot: 'S0', first: 'x', second: 'x' });
    let reads = 0; const failure = new Error('second authored read');
    installReadProbe(view.exposed, () => { if (++reads === 2) throw failure; return 'new-first'; });
    expect(() => view.update()).toThrow(failure);
    expect(reads).toBe(2);
    await view.slot('S1');
    expect(snapshot(view.host)).toEqual({ authored: undefined, slot: undefined, first: undefined, second: undefined });
  });
  it('rebinds the current slot after authored ViewIntent detachment without reviving the old root', async () => {
    const view = await mount();
    const oldOutput = view.host.querySelector('output');
    expect(oldOutput?.textContent).toBe('A');
    method(view.exposed, 'write')('B');
    view.input.present = false; await flush();
    expect(view.host.querySelector('output')).toBeNull();
    await view.slot('S1');
    expect(view.host.querySelector('[data-native-slot]')).toBeNull();
    view.input.present = true; await flush();
    expect(snapshot(view.host)).toMatchObject({ authored: 'B', slot: 'S1' });
    expect(view.host.querySelector('output')).not.toBe(oldOutput);
    expect(oldOutput?.isConnected).toBe(false);
  });
  it('retains instance state across native KeepAlive epochs and invalidates saved methods on destruction', async () => {
    const view = await mount(compile(), 'none', true);
    const write = method(view.exposed, 'write');
    write('B'); view.update(); await flush();
    view.input.visible = false; await flush();
    expect(view.host.querySelector('output')).toBeNull();
    view.input.slot = 'S1'; view.input.visible = true; await flush();
    expect(snapshot(view.host)).toMatchObject({ authored: 'B', slot: 'S1' });
    expect(method(view.child, 'getExposes')()).toMatchObject({ write: Reflect.get(view.exposed as object, 'write') });
    const oldRoot = view.host.querySelector('output');
    expect(oldRoot).not.toBeNull();
    await view.close();
    expect(() => write('C')).toThrow();
    view.update(); await flush();
    expect(oldRoot?.isConnected).toBe(false);
    expect(view.host.isConnected).toBe(false);
  });
});

describe('Vue2 generated graph strict boundary (separate from behavior/transpilation)', () => {
  it('checks every actual emitted source with real Vue2 declarations and no diagnostic filtering', async () => {
    const module = compile();
    const evidence = moduleEvidence.get(module);
    const files = graph(module);
    files.set('Consumer.ts', `import Vue from 'vue';
import Component from './Component.js';
export const consumer = new Vue({render(h){return h(Component, {scopedSlots:{default:()=>[h('em','native')]}});}});`);
    // Persist the exact authored native consumer and actual generated graph before
    // temporary strict-program files are removed by afterEach, even on failure.
    for (const [file, source] of files) artifact(evidence, `strict/files/${file}`, source);
    const parent = path.join(path.dirname(fileURLToPath(import.meta.url)), 'generated-modules');
    await mkdir(parent, { recursive: true });
    const directory = await mkdtemp(path.join(parent, 'vue2-commit-strict-'));
    cleanups.push(() => rm(directory, { recursive: true, force: true }));
    for (const [file, source] of files) {
      const destination = path.join(directory, file);
      await mkdir(path.dirname(destination), { recursive: true }); await writeFile(destination, source);
    }
    const repository = fileURLToPath(new NodeURL('../../../', import.meta.url));
    const config = ts.readConfigFile(path.join(repository, 'tsconfig.json'), ts.sys.readFile);
    if (config.error) {
      artifactJson(evidence, 'strict/diagnostics.json', [diagnosticRecord(config.error)]);
      throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
    }
    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, repository);
    const vue2 = createRequire(new NodeURL('../../adapters/vue2/package.json', import.meta.url));
    const rootNames = [...files.keys()].map(file => path.join(directory, file));
    const options: ts.CompilerOptions = {
      ...parsed.options, paths: { ...parsed.options.paths,
        vue: [path.dirname(vue2.resolve('vue/package.json'))] },
      noEmit: true, strict: true, skipLibCheck: false, allowJs: true, checkJs: true,
    };
    artifactJson(evidence, 'strict/request.json', { rootNames, options, typescript: ts.version,
      vueDeclarationRoot: path.dirname(vue2.resolve('vue/package.json')) });
    const program = ts.createProgram(rootNames, options);
    const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)].map(diagnosticRecord);
    artifactJson(evidence, 'strict/diagnostics.json', diagnostics);
    artifactJson(evidence, 'strict/program.json', program.getSourceFiles().map(file => ({
      file: file.fileName, sha256: createHash('sha256').update(file.text).digest('hex'),
      isDeclarationFile: file.isDeclarationFile,
    })));
    expect(diagnostics, JSON.stringify(diagnostics, null, 2)).toEqual([]);
  });
});
