import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../../experiments/material-specializer/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('modules.json', root), 'utf8'));
const shaders = ['lens.vert', 'lens.frag'].map((name, index) => {
  const value = readFileSync(new URL(`kernels/${name}`, root), 'utf8');
  if (createHash('sha256').update(value).digest('hex') !== manifest[index].sourceLiteralSha256)
    throw new Error(`Audited kernel changed: ${name}`);
  return value;
});
const license = readFileSync(new URL('kernels/LICENSE', root), 'utf8');
const output = `// Generated by scripts/build/generate-web-material-kernel.mjs. Do not edit.\n// Unmodified liquidGL shader literals at 88f681ab7035fd55b04f63edff1841e32c4199e9.\n/*!\n${license.replaceAll('*/', '* /')}\n*/\nexport const vertex = ${JSON.stringify(shaders[0])};\nexport const fragment = ${JSON.stringify(shaders[1])};\nexport const uniformNames = ${JSON.stringify(manifest[1].uniforms.map((row) => row[1]))} as const;\n`;
const target = new URL(
  '../../packages/adapters/base/src/material/liquidgl-kernel.generated.ts',
  import.meta.url
);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw new Error('Generated Web material kernel drift');
} else writeFileSync(target, output);
