#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

// These are neutral, existing host primitives. This list is a closed compiler
// asset input, not an authored source loader or a Runtime/Adapter dependency.
const sources = [
  'packages/adapters/base/src/events/pointer-sample.ts',
  'packages/adapters/base/src/gestures/web-move-click-arbitration.ts',
  'packages/adapters/base/src/gestures/web-move-gesture-host.ts',
  'packages/adapters/base/src/gestures/web-axis-input-host.ts',
  'packages/modules/positioning/src/available-layout.ts',
  'packages/modules/positioning/src/caps.ts',
  'packages/modules/positioning/src/web/root-space-observer.ts',
  'packages/modules/positioning/src/web/translation-composition.ts',
  'packages/modules/positioning/src/web/available-layout-host.ts',
  'packages/modules/positioning/src/web/available-space-host.ts',
  'packages/modules/positioning/src/geometry/target-alignment.ts',
  'packages/modules/positioning/src/web/target-alignment-host.ts',
  'packages/modules/positioning/src/web/border-box-size-lease.ts',
  'packages/modules/positioning/src/web/owned-style-lease.ts',
  'packages/modules/overlay/src/target-alignment-binding.ts',
  'packages/modules/anatomy/src/types.ts',
  'packages/modules/boundary/src/types.ts',
  'packages/core/src/anatomy.ts',
  'packages/core/src/overlay.ts',
  'packages/core/src/axis-input.ts',
  'packages/core/src/move.ts',
  'packages/core/src/positioning.ts',
  'packages/core/src/presence-presentation.ts',
  'packages/core/src/resident-motion.ts',
  'packages/core/src/effects/types.ts',
  'packages/core/src/spec/feedback/style.ts',
  'packages/modules/feedback/src/presence/controller.ts',
  'packages/modules/feedback/src/presence/projector.ts',
  'packages/modules/feedback/src/presence/sink.ts',
  'packages/modules/feedback/src/motion/sampler.ts',
  'packages/adapters/base/src/motion/web-presence-presentation.ts',
  'packages/adapters/base/src/platform/web-preference-source.ts',
  'packages/adapters/base/src/platform/web-owned-decoration-stage.ts',
];
const root = new URL('../../', import.meta.url);
const inputs = sources.map((file) => {
  const contents = readFileSync(new URL(file, root), 'utf8');
  return { file, sha256: createHash('sha256').update(contents).digest('hex'), contents };
});
const output = new URL('packages/compiler/src/native-support/web-host-sources.generated.ts', root);
const outputPath = fileURLToPath(output);
const rawContents =
  '// Generated by scripts/compiler/generate-web-host-sources.mjs.\n' +
  '// Canonical host source snapshots; no authored prototype code is stored here.\n' +
  'export const canonicalWebHostSources = ' +
  JSON.stringify(inputs, null, 2) +
  ' as const;\n';
// Match the repository formatter so lint-staged cannot stale a generated asset.
const contents = await format(rawContents, {
  ...((await resolveConfig(outputPath)) ?? {}),
  filepath: outputPath,
});
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== contents)
    throw new Error(
      'Canonical Web host compiler assets are stale; regenerate ' + fileURLToPath(output)
    );
} else writeFileSync(output, contents);
