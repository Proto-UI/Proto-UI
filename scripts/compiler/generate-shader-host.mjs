import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const source = new URL(
  '../../packages/adapters/base/src/material/shader-webgl2-host.ts',
  import.meta.url
);
const target = new URL(
  '../../packages/compiler/src/native-shader-host.generated.ts',
  import.meta.url
);
const contents = await readFile(source, 'utf8');
const sceneContents = await readFile(
  new URL('../../packages/adapters/base/src/material/shader-scene-host.ts', import.meta.url),
  'utf8'
);
const kernels = await import(source.href);
const digest = (text) => createHash('sha256').update(text, 'utf8').digest('hex');
const names = [
  'SHADER_VERTEX_V1',
  'SHADER_COPY_RGBA8_V1',
  'SHADER_TINT_RGBA8_V1',
  'SHADER_PUBLISH_SRGB_V1',
];
const identities = Object.fromEntries(names.map((name) => [name, digest(kernels[name])]));
const raw =
  '// Generated by scripts/compiler/generate-shader-host.mjs. Do not edit.\n' +
  '// First-party MIT host resource atom; exact canonical source retained, no graph interpreter.\n' +
  `export const nativeShaderHostSource = ${JSON.stringify(contents)};\n` +
  `export const nativeShaderSceneHostSource = ${JSON.stringify(sceneContents)};\n` +
  `export const nativeShaderSceneHostSha256 = ${JSON.stringify(digest(sceneContents))};\n` +
  `export const nativeShaderHostSha256 = ${JSON.stringify(digest(contents))};\n` +
  `export const nativeShaderKernelSha256 = ${JSON.stringify(identities, null, 2)} as const;\n`;
const generated = await format(raw, {
  ...(await resolveConfig(fileURLToPath(target))),
  parser: 'typescript',
});
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8').catch(() => '')) !== generated) {
    process.stderr.write(
      'Native shader host artifact drift: run node scripts/compiler/generate-shader-host.mjs\n'
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(target, generated);
  process.stdout.write(`Generated ${fileURLToPath(target)}\n`);
}
